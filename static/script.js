/*calculating pack years automatically */

const smokingYearsInput = document.getElementById("smoking_years");
const cigarettesPerDayInput = document.getElementById("cigarettes_per_day");
const packYearsInput = document.getElementById("pack_years");

function calculatePackYears() {
    const smokingYears = Number(smokingYearsInput.value);
    const cigarettesPerDay = Number(cigarettesPerDayInput.value);

    if (smokingYears > 0 && cigarettesPerDay > 0) {
        const packYears = (smokingYears * cigarettesPerDay) / 20;
        packYearsInput.value = packYears.toFixed(2);
    } else {
        packYearsInput.value = "0";
    }
}

smokingYearsInput.addEventListener("input", calculatePackYears);
cigarettesPerDayInput.addEventListener("input", calculatePackYears);